let current: Lang = (() => {
  try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh' } catch { return 'zh' }
})()

export const getLang = (): Lang => current

export function setLang(l: Lang) {
  current = l
  try { localStorage.setItem(STORAGE_KEY, l) } catch { /* 忽略隐私模式 */ }
  window.dispatchEvent(new Event('slt-language-change'))
}

export function t(key: I18nKey): string {
  return (current === 'en' ? en : zh)[key] ?? zh[key] ?? key
}
