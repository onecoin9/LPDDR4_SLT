"""Generate frontend/firmware contracts from the reviewed backend timing catalogue."""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("timing_catalog", ROOT / "backend/app/timing_catalog.py")
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
import sys
sys.path.insert(0, str(ROOT / 'backend'))
from app.timing_ns import CATALOG_NS


def contents():
    ts = "// Generated by desktop/generate_timing_catalog.py; do not edit by hand.\n"
    ts += "export const TIMING_SCHEMA = 1\nexport const TIMING_CAPABILITY = 'T1:'\n"
    ts += "export const TIMING_CATALOG = " + json.dumps(module.CATALOG, ensure_ascii=False, indent=2) + " as const\n"
    ts += "export const TIMING_BY_KEY = new Map<string, typeof TIMING_CATALOG[number]>(TIMING_CATALOG.map(r => [r.key, r]))\n"
    ts += "export const LEGACY_TIMING_KEYS = new Set(" + json.dumps(sorted(module.LEGACY_KEYS), ensure_ascii=False) + ")\n"
    ts += "export const TIMING_NS_CATALOG = " + json.dumps(CATALOG_NS, ensure_ascii=False, indent=2) + " as const\n"
    ts += "export const TIMING_NS_BY_KEY = new Map<string, typeof TIMING_NS_CATALOG[number]>(TIMING_NS_CATALOG.map(r => [r.key, r]))\n"
    inc = "/* Generated MT6785 timing registry v1. IDs are wire ABI; never reorder. */\n"
    for r in module.CATALOG:
        kind = "NS" if r["unit"] == "ns" else "REG"
        inc += f"HSG_TREG_{kind}({r['id']}, {r['key']}, DRAMC_REG_{r['register']}, {r['field']}, {r['width']}, {r['min'] * r['scale']}, {r['max'] * r['scale']})\n"
    return ts, inc


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--firmware-dir", type=Path)
    args = ap.parse_args()
    ts, inc = contents()
    outputs = [(ROOT / "frontend/src/types/timingCatalog.ts", ts)]
    if args.firmware_dir:
        outputs.append((args.firmware_dir / "inc/hsg_timing_registry.inc", inc))
        ns = '/* Generated ns v2 metadata. Raw v1 IDs remain stable. */\n'
        ns += ''.join(f"HSG_TNS({r['id']}, {r['width']}, {r['halfId']})\n" for r in CATALOG_NS)
        outputs.append((args.firmware_dir / 'inc/hsg_timing_ns_registry.inc', ns))
    for path, value in outputs:
        if args.check:
            if path.read_text(encoding="utf-8") != value:
                raise SystemExit(f"Timing catalogue differs: {path}")
        else:
            path.write_text(value, encoding="utf-8", newline="\n")
    print(f"Verified/generated {len(module.CATALOG)} timing fields")
